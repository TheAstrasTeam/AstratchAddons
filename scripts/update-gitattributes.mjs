import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const addonsDir = join("addons");
const lines = ["# Auto-generated by scripts/update-gitattributes.mjs", "# Marks compiled main.js of TypeScript addons as generated (no GitHub diff)"];

for (const name of readdirSync(addonsDir).sort()) {
  const manifestPath = join(addonsDir, name, "manifest.json");
  if (!existsSync(manifestPath)) continue;
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  if (manifest.typescript === true) {
    lines.push(`${join(addonsDir, name, "main.js").replaceAll("\\", "/")} linguist-generated=true`);
  }
}

writeFileSync(".gitattributes", `${lines.join("\n")}\n`);
console.log(`[gitattributes] wrote ${lines.length - 2} generated entries`);
